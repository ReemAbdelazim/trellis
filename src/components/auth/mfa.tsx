"use client";

import { useEffect, useRef, useState } from "react";
import { Copy, ShieldCheck } from "lucide-react";
import { toast } from "sonner";
import { createClient } from "@/lib/supabase/client";
import { Button } from "@/components/ui/button";
import { Input, Label } from "@/components/ui/input";
import { PageLoader, Spinner } from "@/components/ui/misc";

/** The person's verified authenticator, if they have one. */
export async function verifiedTotpFactor() {
  const { data, error } = await createClient().auth.mfa.listFactors();
  if (error) throw error;
  return data.totp.find((f) => f.status === "verified") ?? null;
}

function CodeForm({ onSubmit, label = "Verify" }: { onSubmit: (code: string) => Promise<string | null>; label?: string }) {
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [pending, setPending] = useState(false);
  return (
    <form
      className="space-y-3"
      onSubmit={async (e) => {
        e.preventDefault();
        setPending(true);
        setError(await onSubmit(code));
        setPending(false);
      }}
    >
      <div>
        <Label htmlFor="mfa-code">6-digit code from your authenticator app</Label>
        <Input
          id="mfa-code"
          value={code}
          onChange={(e) => setCode(e.target.value.replace(/\D/g, "").slice(0, 6))}
          inputMode="numeric"
          autoComplete="one-time-code"
          autoFocus
          placeholder="123456"
          className="text-center text-lg tracking-[0.4em]"
        />
      </div>
      {error && <p className="text-[13px] text-danger">{error}</p>}
      <Button type="submit" variant="primary" size="md" className="w-full justify-center" disabled={code.length !== 6 || pending}>
        {pending && <Spinner size={16} className="text-current" />}
        {label}
      </Button>
    </form>
  );
}

async function verifyCode(factorId: string, code: string) {
  const { error } = await createClient().auth.mfa.challengeAndVerify({ factorId, code });
  if (!error) return null;
  return /invalid|expired/i.test(error.message) ? "That code didn't work. Check the time on your phone and try the newest code." : error.message;
}

/** Asks for the current code from an already set-up authenticator. */
export function MfaChallenge({ factorId, onDone }: { factorId: string; onDone: () => void }) {
  return (
    <CodeForm
      onSubmit={async (code) => {
        const error = await verifyCode(factorId, code);
        if (!error) onDone();
        return error;
      }}
    />
  );
}

/**
 * Sets up an authenticator app: shows a QR code (and the key for typing in by
 * hand), then confirms the first code. `replacing` removes that factor once the
 * new one works.
 */
export function MfaEnroll({ onDone, replacing }: { onDone: () => void; replacing?: string }) {
  const [enrollment, setEnrollment] = useState<{ id: string; qr: string; secret: string } | null>(null);
  const [error, setError] = useState<string | null>(null);
  const started = useRef(false);

  useEffect(() => {
    if (started.current) return;
    started.current = true;
    (async () => {
      const mfa = createClient().auth.mfa;
      // Clear half-finished setups from earlier attempts.
      const { data: factors } = await mfa.listFactors();
      for (const f of factors?.all ?? []) {
        if (f.status === "unverified") await mfa.unenroll({ factorId: f.id });
      }
      const { data, error } = await mfa.enroll({
        factorType: "totp",
        friendlyName: `Authenticator ${new Date().toISOString().slice(0, 16)}`,
      });
      if (error) setError(error.message);
      else setEnrollment({ id: data.id, qr: data.totp.qr_code, secret: data.totp.secret });
    })();
  }, []);

  if (error) return <p className="text-[13px] text-danger">{error}</p>;
  if (!enrollment) return <PageLoader />;

  return (
    <div className="space-y-4">
      <ol className="list-decimal space-y-1 pl-5 text-sm text-muted">
        <li>Open an authenticator app (Google Authenticator, Microsoft Authenticator, 1Password…).</li>
        <li>Scan this QR code, or enter the key by hand.</li>
        <li>Type the 6-digit code it shows.</li>
      </ol>
      <div className="flex justify-center">
        {/* The QR code is an SVG data URL generated by Supabase. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src={enrollment.qr} alt="QR code for your authenticator app" width={180} height={180} className="rounded-lg bg-white p-2" />
      </div>
      <button
        type="button"
        onClick={() => navigator.clipboard.writeText(enrollment.secret).then(() => toast.success("Key copied"))}
        className="flex w-full items-center justify-center gap-2 rounded-md bg-surface-2 px-3 py-2 font-mono text-xs break-all text-muted hover:text-text"
        aria-label="Copy setup key"
      >
        {enrollment.secret} <Copy size={13} className="shrink-0" />
      </button>
      <CodeForm
        label="Turn on two-factor"
        onSubmit={async (code) => {
          const error = await verifyCode(enrollment.id, code);
          if (error) return error;
          if (replacing) await createClient().auth.mfa.unenroll({ factorId: replacing });
          onDone();
          return null;
        }}
      />
    </div>
  );
}

export function MfaBadge() {
  return (
    <span className="inline-flex items-center gap-1 rounded-full bg-success-soft px-2 py-0.5 text-xs font-medium text-success">
      <ShieldCheck size={12} /> Two-factor on
    </span>
  );
}
